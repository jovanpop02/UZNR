// Refreshes src/data/instagram.js from the Instagram Graph API.
//
// Runs at build time, never in the browser. That is deliberate: an access token
// shipped in frontend JS is readable by anyone who opens devtools, so the token
// stays in the build environment and only the resulting post shortcodes are
// published.
//
// Setup (one time):
//   1. Convert instagram.com/uznr.me to a Business or Creator account.
//   2. Create a Meta app and generate a long-lived Instagram access token.
//   3. On Netlify: Site configuration → Environment variables →
//      INSTAGRAM_TOKEN = <the token>
//
// Without the variable set, the committed list is left alone — so the section
// keeps working exactly as it does today until the token exists.
//
// Long-lived tokens expire after ~60 days. `npm run refresh-instagram-token`
// exchanges the current one for a fresh 60-day token; run it before expiry and
// paste the new value into Netlify.

import { writeFile, access } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const TOKEN = process.env.INSTAGRAM_TOKEN
const PROFILE_URL = 'https://www.instagram.com/uznr.me/'
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data', 'instagram.js')
const MAX = 6

const q = (s) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'"

function render(codes, generated) {
  return `// Latest posts from instagram.com/uznr.me.
//
// ${generated
    ? 'Generated by scripts/fetch-instagram.mjs from the Graph API — do not edit by hand.'
    : 'Maintained by hand. Set INSTAGRAM_TOKEN to have the build refresh this file;\n// see scripts/fetch-instagram.mjs. To update manually, copy the shortcode out of\n// a post URL (instagram.com/p/<shortcode>/) and replace an entry below.'}
// Rendered through Instagram's official embed, which needs no credentials.
export const profileUrl = ${q(PROFILE_URL)}

export const posts = [
${codes.map((c) => `  { code: ${q(c)} },`).join('\n')}
]
`
}

function shortcode(permalink) {
  const m = String(permalink).match(/\/(?:p|reel|tv)\/([A-Za-z0-9_-]+)/)
  return m ? m[1] : null
}

async function keepExisting(reason) {
  console.warn(`[fetch-instagram] ${reason} — keeping committed list`)
  try {
    await access(OUT)
  } catch {
    console.error('[fetch-instagram] no committed list to fall back to')
    process.exitCode = 1
  }
}

async function main() {
  if (!TOKEN) {
    console.log('[fetch-instagram] INSTAGRAM_TOKEN not set — keeping committed list')
    return
  }

  const url = new URL('https://graph.instagram.com/me/media')
  url.searchParams.set('fields', 'permalink,timestamp,media_type')
  url.searchParams.set('limit', String(MAX * 2))
  url.searchParams.set('access_token', TOKEN)

  let payload
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(20000) })
    payload = await res.json()
    if (!res.ok || payload.error) {
      throw new Error(payload?.error?.message || `HTTP ${res.status}`)
    }
  } catch (err) {
    // An expired token must not fail the deploy — the site still renders the
    // previously committed posts.
    return keepExisting(`Graph API request failed (${err.message})`)
  }

  const codes = (payload.data || [])
    .map((item) => shortcode(item.permalink))
    .filter(Boolean)
    .slice(0, MAX)

  if (!codes.length) return keepExisting('API returned no usable posts')

  await writeFile(OUT, render(codes, true), 'utf8')
  console.log(`[fetch-instagram] wrote ${codes.length} posts (newest: ${codes[0]})`)
}

main()
